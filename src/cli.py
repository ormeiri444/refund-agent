"""Command line: `python -m src.cli decide <csv>` and `... backtest`."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

from src import settings
from src.data.normalize import load_requests
from src.queue import run_system
from src.llm.client import LLMClient
from src.llm.extractor import FactExtractor
from src.logging_setup import get_logger, setup_logging
from src.policy.backtest import DEFAULT_CAPS, cap_table, format_backtest, format_cap_table, run_backtest
from src.policy.engine import FactProvider, decisions_to_frame, unknown_fact_provider
from src.policy.store import load_policy

log = get_logger("cli")


def build_fact_provider(no_llm: bool) -> FactProvider:
    """The LLM reads notes only when a rule needs it; without a key every fact is unknown."""
    if no_llm:
        log.info("facts: disabled (--no-llm); note-based facts unknown")
        return unknown_fact_provider
    client = LLMClient()
    if not client.available:
        print("LLM unavailable (no ANTHROPIC_API_KEY): note-based facts unknown, those requests route to a person.")
        log.info("facts: LLM unavailable; facts unknown")
    else:
        log.info("facts: LLM extractor on model=%s (cache %s, seed %s)", client.model, settings.CACHE_PATH, settings.CACHE_SEED_PATH)
    return FactExtractor(client)


def llm_cost_text(provider: FactProvider, n_requests: int) -> str:
    stats = getattr(provider, "stats", None)
    if not stats:
        return "LLM calls: 0 (facts disabled)"
    calls, cost = stats["calls"], stats["cost_usd"]
    per_call = cost / calls if calls else 0.0
    return (f"LLM calls: {calls} ({stats['cache_hits']} cache hits), spend ${cost:.4f}, "
            f"${per_call:.5f} per call, ${cost / max(n_requests, 1):.5f} per decision over {n_requests} requests")


def summary_text(frame: pd.DataFrame, policy_version: int) -> str:
    lines = [f"policy v{policy_version}: {len(frame)} requests"]
    by_outcome = frame.groupby("outcome").agg(n=("request_id", "count"), usd=("amount_usd", "sum"))
    for outcome, row in by_outcome.iterrows():
        lines.append(f"  {outcome:<8} {int(row.n):>4}  ${row.usd:,.2f}")
    lines.append("by rule:")
    by_rule = frame.groupby(["outcome", "rule_id"]).size().sort_values(ascending=False)
    for (outcome, rule_id), n in by_rule.items():
        lines.append(f"  {outcome:<8} {n:>4}  {rule_id}")
    return "\n".join(lines)


def cmd_decide(args: argparse.Namespace) -> int:
    csv_path = Path(args.csv)
    if not csv_path.exists():
        print(f"error: file not found: {csv_path}", file=sys.stderr)
        return 2
    policy = load_policy(args.policy)
    provider = build_fact_provider(args.no_llm)
    out = Path(args.out)
    decisions = run_system(csv_path, policy, provider, decisions_path=out)   # decisions + the request snapshot the app reads
    frame = decisions_to_frame(decisions)
    print(summary_text(frame, policy.version))
    print(llm_cost_text(provider, len(decisions)))
    print(f"wrote {len(decisions)} decisions to {out}")
    return 0


LINE_HEADER = "## 8. The line: backtest of the policy on history"


def write_the_line(findings_path: Path, body: str) -> None:
    """Replace (or append) the 'The line' section of the findings document."""
    text = findings_path.read_text() if findings_path.exists() else "# EDA findings\n"
    head = text.split(LINE_HEADER)[0].rstrip() + "\n\n"
    findings_path.write_text(head + LINE_HEADER + "\n\n" + body.rstrip() + "\n")


def cmd_backtest(args: argparse.Namespace) -> int:
    policy_dir = Path(args.policy_dir) if args.policy_dir else None
    policy = load_policy(args.policy, policy_dir=policy_dir)
    history = load_requests(settings.DATA_DIR / "history.csv")
    provider = build_fact_provider(args.no_llm)
    result = run_backtest(history, policy, provider)
    rows = cap_table(history, policy, DEFAULT_CAPS, provider)
    report = format_backtest(result) + "\n" + llm_cost_text(provider, result.n)
    table = format_cap_table(rows)
    print(report)
    print("\nIf the auto-approve cap were:")
    print(table)
    if not args.no_write:
        facts_note = "without note facts (no LLM)" if args.no_llm else "with note facts"
        cap_rule = next((r for r in policy.rules if r.id == "over_cap"), None)
        cap_now = cap_rule.when[0].value if cap_rule else "n/a"
        body = "\n".join([
            f"Generated by `refund-agent backtest` ({facts_note}). Policy v{policy.version}, cap in force: ${cap_now}.",
            "",
            "```", report, "```",
            "",
            "If the auto-approve cap were:",
            "",
            table,
            "",
            "**Bad** = the policy approves and the case later charged back, carried a fraud flag the fraud team did not confirm, or the final human decision "
            "(after appeals) was rejected or partial. **Detectable** = a note or a fraud flag was there to be read; those make the "
            "verdict FAIL. **Undetectable** = nothing in the request could have caught it; listed as accepted risk.",
            "",
            "**Rollback after launch.** Tier 1: one chargeback or fraud confirmation on an auto-approved request, the manager "
            "disables the rule that fired. Tier 2: if the chargeback rate on auto-approvals over the trailing 4 weeks exceeds "
            "the historical human rate (3.7%), or one week's auto-approved dollars exceed 1.5x the expected per-week baseline "
            "above, the manager publishes a policy whose first rule is ALWAYS route.",
        ])
        write_the_line(settings.ROOT_DIR / "docs" / "eda" / "findings.md", body)
        print(f"\nwrote 'The line' section to docs/eda/findings.md")
    return 0 if result.verdict == "PASS" else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="refund_agent", description="Refund triage: approve by rule or route to a person.")
    sub = parser.add_subparsers(dest="command", required=True)

    p_decide = sub.add_parser("decide", help="decide every request in a CSV with the same columns as pending.csv")
    p_decide.add_argument("csv")
    p_decide.add_argument("--policy", type=int, default=None, help="policy version (default: latest)")
    p_decide.add_argument("--no-llm", action="store_true", help="do not call the LLM; every note-based fact is unknown")
    p_decide.add_argument("--out", default=str(settings.SYSTEM_DECISIONS_PATH))
    p_decide.set_defaults(func=cmd_decide)

    p_bt = sub.add_parser("backtest", help="replay a policy on data/history.csv; exit 1 if it would approve a detectable bad case")
    p_bt.add_argument("--policy", type=int, default=None, help="policy version (default: latest)")
    p_bt.add_argument("--policy-dir", default=None, help="directory of policy files (default: policies/)")
    p_bt.add_argument("--no-llm", action="store_true", help="do not call the LLM; every note-based fact is unknown")
    p_bt.add_argument("--no-write", action="store_true", help="do not update docs/eda/findings.md")
    p_bt.set_defaults(func=cmd_backtest)

    args = parser.parse_args(argv)
    setup_logging()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
